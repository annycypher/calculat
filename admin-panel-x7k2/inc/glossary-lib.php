        $chips[] = '<a class="glossary-chip" href="/glossary/' . h($o['slug']) . '.html">' . h($o['term']) . '</a>';
        if (count($chips) >= 6) { break; }
    }
    $chips[] = '<a class="glossary-chip" href="/glossary/">Весь глоссарий</a>';

    $tool = '';
    if ($t['tool_url'] !== '') {
        $label = $t['tool_title'] !== '' ? (string)$t['tool_title'] : 'калькулятор';
        $tool = '<h2 class="section-title">Посчитать на своих числах</h2>' . "\n"
            . '  <p>Подставьте свою сумму, ставку и срок в ' . h($label) . ' — увидите размер платежа,'
            . ' график и общую переплату.</p>' . "\n"
            . '  <p><a class="btn btn-glass" href="' . h($t['tool_url']) . '">' . h($label) . '</a></p>';
    }

    return glossary_style() . "\n"
        . '<div class="container tool-hero">' . "\n"
        . '  <nav class="breadcrumbs"><a href="/">Главная</a> / <a href="/glossary/">Глоссарий</a> / '
        . h($t['term']) . '</nav>' . "\n"
        . '  <h1>' . h($t['term']) . '</h1>' . "\n"
        . ($t['short'] !== '' ? '  <p class="tool-meta">' . h($t['short']) . '</p>' . "\n" : '')
        . '  <!--EDIT:updated--><p class="tool-meta" style="margin-top:6px">Обновлено: '
        . h(glossary_date_text((string)$t['updated'])) . '</p><!--/EDIT:updated-->' . "\n"
        . '</div>' . "\n"
        . '<!--SLOT:banner-top-->' . "\n" . '<!--/SLOT:banner-top-->' . "\n"
        . '<div class="container section">' . "\n"
        . '  <h2 class="section-title">Что это простыми словами</h2>' . "\n  "
        . $t['text'] . "\n"
        . ($t['example'] !== ''
            ? '  <h2 class="section-title">Пример на числах</h2>' . "\n  <p>" . h($t['example']) . "</p>\n" : '')
        . ($tool !== '' ? '  ' . $tool . "\n" : '')
        . '</div>' . "\n"
        . '<div class="container section">' . "\n"
        . '  <h2 class="section-title">Рядом в глоссарии</h2>' . "\n"
        . '  <p class="glossary-abc">' . implode('', $chips) . '</p>' . "\n"
        . '</div>' . "\n"
        . '<!--SLOT:banner-footer-->' . "\n" . '<!--/SLOT:banner-footer-->' . "\n"
        . '<!--SLOT:ads-before-footer-->' . "\n" . '<!--/SLOT:ads-before-footer-->';
}

/** Собрать и записать страницы глоссария: указатель + по странице на каждый термин,
    обновить sitemap.xml и поставить файлы в реестр «к заливке».
    Возвращает ['ok','error','steps'=>[['what','backup']],'notes'=>[],'files'=>[]]. */
function glossary_publish(): array
{
    $terms = glossary_all();
    $bad   = array('ok' => false, 'error' => '', 'steps' => array(), 'notes' => array(), 'files' => array());
    if (count($terms) === 0) {
        $bad['error'] = 'В глоссарии пока нет ни одного термина — сначала добавьте термин (или нажмите «Добавить первые термины»).';
        return $bad;
    }

    $steps = array();
    $notes = array();
    $files = array();

    /* 1. Указатель */
    $hubPage = array(
        'title'       => 'Глоссарий CalcDoc — денежные термины простыми словами',
        'description' => 'Глоссарий CalcDoc: аннуитетный и дифференцированный платёж, капитализация процентов, '
            . 'эффективная ставка, ПСК, первоначальный взнос, налоговый вычет, НДФЛ и другие термины — простыми словами, '
            . 'с примерами и ссылками на калькуляторы.',
        'url'         => GLOSSARY_SITE . '/glossary/',
    );
    $hub = glossary_page($hubPage, glossary_hub_body($terms), glossary_jsonld_hub($terms));
    if (!$hub['ok']) { $bad['error'] = $hub['error']; return $bad; }

    $write = file_write_safe(SITE_ROOT . '/' . GLOSSARY_DIR . '/index.html', $hub['html']);
    if (!$write['ok']) { $bad['error'] = $write['error']; return $bad; }
    $files[] = '/' . GLOSSARY_DIR . '/index.html';
    $steps[] = array('what' => ($write['created'] ? 'Собран указатель ' : 'Обновлён указатель ')
        . '/' . GLOSSARY_DIR . '/index.html', 'backup' => $write['backup']);

    /* 2. По странице на термин */
    foreach ($terms as $t) {
        $page = array(
            'title'       => $t['term'] . ' — что это простыми словами | CalcDoc',
            'description' => mb_substr(trim((string)$t['short']), 0, 200),
            'url'         => GLOSSARY_SITE . '/glossary/' . $t['slug'] . '.html',
        );
        $pageHtml = glossary_page($page, glossary_term_body($t, $terms), glossary_jsonld_term($t));
        if (!$pageHtml['ok']) { $notes[] = 'Термин «' . $t['term'] . '»: ' . $pageHtml['error']; continue; }
        $rel  = '/' . GLOSSARY_DIR . '/' . $t['slug'] . '.html';
        $wrote = file_write_safe(SITE_ROOT . $rel, $pageHtml['html']);
        if (!$wrote['ok']) { $notes[] = 'Термин «' . $t['term'] . '»: ' . $wrote['error']; continue; }
        $files[] = $rel;
        $steps[] = array('what' => ($wrote['created'] ? 'Собран термин ' : 'Обновлён термин ') . $rel,
            'backup' => $wrote['backup']);
    }

    /* 3. Карта сайта: указатель и каждый термин */
    $sm = sitemap_update(GLOSSARY_SITE . '/glossary/', date('Y-m-d'));
    if (!$sm['ok']) { $notes[] = 'Указатель в карте сайта: ' . $sm['error']; }
    else {
        $files[] = '/sitemap.xml';
        $steps[] = array('what' => 'sitemap.xml: ' . $sm['changed'], 'backup' => $sm['backup']);
    }
    foreach ($terms as $t) {
        $smT = sitemap_update(GLOSSARY_SITE . '/glossary/' . $t['slug'] . '.html',
            trim((string)$t['updated']) !== '' ? (string)$t['updated'] : date('Y-m-d'));
        if (!$smT['ok']) { $notes[] = 'Термин «' . $t['term'] . '» в карте сайта: ' . $smT['error']; }
    }

    /* 4. Реестр «к заливке» — владелец увидит эти файлы в разделе «Публикация» */
    foreach (array_unique($files) as $rel) { deploy_changes_add($rel); }

    log_action('Глоссарий: собраны страницы сайта', count($terms) . ' терминов');
    return array('ok' => true, 'error' => '', 'steps' => $steps, 'notes' => $notes, 'files' => array_unique($files));
}

/** Что уже лежит на сайте: указатель и страницы терминов (для раздела панели). */
function glossary_pages_state(array $terms): array
{
    $hub = SITE_ROOT . '/' . GLOSSARY_DIR . '/index.html';
    $out = array('hub' => array('rel' => '/' . GLOSSARY_DIR . '/index.html', 'exists' => is_file($hub),
        'at' => is_file($hub) ? date('d.m.Y H:i', (int)@filemtime($hub)) : '', 'size' => is_file($hub) ? (int)@filesize($hub) : 0),
        'terms' => array());
    foreach ($terms as $t) {
        $f = SITE_ROOT . '/' . GLOSSARY_DIR . '/' . $t['slug'] . '.html';
        $out['terms'][$t['slug']] = array('exists' => is_file($f),
            'at' => is_file($f) ? date('d.m.Y H:i', (int)@filemtime($f)) : '',
            'size' => is_file($f) ? (int)@filesize($f) : 0);
    }
    return $out;
}

/** Сколько страниц терминов лежит на сайте. */
function glossary_published_count(array $terms): int
{
    $n = 0;
    foreach ($terms as $t) {
        if (is_file(SITE_ROOT . '/' . GLOSSARY_DIR . '/' . $t['slug'] . '.html')) { $n++; }
    }
    return $n;
}


