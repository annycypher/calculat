/** Дописать в данные термины, которых там ещё нет (кнопка «Добавить первые термины» в панели). */
function glossary_seed_add(): array
{
    $have = array();
    foreach (glossary_all() as $t) { $have[$t['slug']] = true; }
    $added = 0;
    foreach (glossary_seed() as $t) {
        $clean = glossary_clean($t);
        if (isset($have[$clean['slug']])) { continue; }
        $save = glossary_save($clean);
        if (!empty($save['ok'])) { $added++; }
    }
    return array('ok' => true, 'added' => $added, 'total' => count(glossary_all()));
}

