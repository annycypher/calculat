/** Файл данных глоссария. */
function glossary_file(): string { return CONTENT_DIR . '/glossary.json'; }

/** Первая буква термина — для алфавитного указателя. */
function glossary_letter(string $term): string
{
    $first = mb_strtoupper(mb_substr(trim($term), 0, 1));
    return $first === '' ? 'А' : $first;
}

/** Текст термина: массив абзацев → HTML. Готовый HTML (теги p/h3/ul) оставляем как есть. */
function glossary_text_html(string $text): string
{
    $text = trim(str_replace(array("\r\n", "\r"), "\n", $text));
    if ($text === '') { return ''; }
    if (preg_match('#<(p|h3|h4|ul|ol|blockquote)\b#i', $text)) { return $text; }
    $out = array();
    foreach (preg_split('/\n{2,}/', $text) ?: array() as $part) {
        $part = trim($part);
        if ($part !== '') { $out[] = '<p>' . h($part) . '</p>'; }
    }
    return implode("\n", $out);
}

/** Сколько слов в тексте термина (без тегов). */
function glossary_words(string $text): int
{
    $plain = trim((string)preg_replace('/\s+/u', ' ', strip_tags($text)));
    if ($plain === '') { return 0; }
    return count(preg_split('/\s+/u', $plain, -1, PREG_SPLIT_NO_EMPTY) ?: array());
}

/** Привести термин к аккуратному виду: обязательные поля, буква, slug. */
function glossary_clean(array $t): array
{
    $term = trim((string)($t['term'] ?? ''));
    $slug = strtolower(trim((string)($t['slug'] ?? '')));
    $slug = preg_replace('/[^a-z0-9-]+/', '-', (string)$slug);
    $slug = trim((string)$slug, '-');
    if ($slug === '') { $slug = slugify($term, 40, 'termin'); }

    return array(
        'slug'       => $slug,
        'term'       => $term,
        'letter'     => glossary_letter($term),
        'short'      => trim((string)($t['short'] ?? '')),
        'text'       => glossary_text_html((string)($t['text'] ?? '')),
        'example'    => trim((string)($t['example'] ?? '')),
        'tool_url'   => trim((string)($t['tool_url'] ?? '')),
        'tool_title' => trim((string)($t['tool_title'] ?? '')),
        'updated'    => trim((string)($t['updated'] ?? '')) !== '' ? trim((string)$t['updated']) : date('Y-m-d'),
    );
}

/** Все термины, по алфавиту (термин → данные). */
function glossary_all(): array
{
    $data  = json_read(glossary_file(), array('version' => 1, 'terms' => array()));
    $terms = isset($data['terms']) && is_array($data['terms']) ? $data['terms'] : array();
    $out   = array();
    foreach ($terms as $t) {
        if (!is_array($t)) { continue; }
        $clean = glossary_clean($t);
        if ($clean['term'] === '') { continue; }
        $out[] = $clean;
    }
    usort($out, function ($a, $b) { return strcoll((string)$a['term'], (string)$b['term']); });
    return $out;
}

/** Один термин по адресу (нет такого — null). */
function glossary_get(string $slug): ?array
{
    foreach (glossary_all() as $t) {
        if ($t['slug'] === $slug) { return $t; }
    }
    return null;
}

/** Записать данные глоссария. */
function glossary_write(array $terms): bool
{
    return json_write(glossary_file(), array('version' => 1, 'terms' => array_values($terms)));
}

/** Добавить или обновить термин. $slug — какой правим (пустой — новый или совпадение по адресу). */
function glossary_save(array $term, string $slug = ''): array
{
    $clean = glossary_clean($term);
    if ($clean['term'] === '') { return array('ok' => false, 'error' => 'У термина нет названия.'); }
    if (mb_strlen($clean['short']) < 10) {
        return array('ok' => false, 'error' => 'Слишком короткое определение: нужна хотя бы одна понятная фраза.');
    }
    if ($clean['text'] === '') { return array('ok' => false, 'error' => 'Пустой текст термина.'); }

    $list  = array();
    $found = false;
    foreach (glossary_all() as $t) {
        if ($slug !== '' && $t['slug'] === $slug) { $list[] = $clean; $found = true; continue; }
        if ($t['slug'] === $clean['slug']) {
            return array('ok' => false, 'error' => 'Такой адрес уже занят термином «' . $t['term'] . '» — выберите другой адрес.');
        }
        $list[] = $t;
    }
    if (!$found) { $list[] = $clean; }

    if (!glossary_write($list)) {
        return array('ok' => false, 'error' => 'Не получилось записать content/glossary.json (права на папку?).');
    }
    return array('ok' => true, 'error' => '', 'slug' => $clean['slug'], 'was' => $found);
}

/** Удалить термин из данных (страницы на сайте остаются — их уберёт следующая публикация). */
function glossary_delete(string $slug): array
{
    $list  = array();
    $found = false;
    foreach (glossary_all() as $t) {
        if ($t['slug'] === $slug) { $found = true; continue; }
        $list[] = $t;
    }
    if (!$found) { return array('ok' => false, 'error' => 'Такого термина нет.'); }
    if (!glossary_write($list)) { return array('ok' => false, 'error' => 'Не получилось записать content/glossary.json.'); }
    return array('ok' => true, 'error' => '');
}

