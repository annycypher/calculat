/** Дата в виде «16 сентября 2026» — как в строках «Обновлено» на сайте. */
function glossary_date_text(string $iso): string
{
    $ts = strtotime($iso);
    if ($ts === false) { return $iso; }
    $months = array(1 => 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
        'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря');
    return date('j', $ts) . ' ' . $months[(int)date('n', $ts)] . ' ' . date('Y', $ts);
}

/** Каркас страницы из образца: <head> с подставленной метой, шапка с меню и хвост с подвалом.
    Возвращает ['ok','error','head','open','close']. */
function glossary_shell(array $page): array
{
    $bad   = array('ok' => false, 'error' => '', 'head' => '', 'open' => '', 'close' => '');
    $donor = SITE_ROOT . '/' . GLOSSARY_DONOR;
    $src   = is_file($donor) ? (string)@file_get_contents($donor) : '';
    if (trim($src) === '') {
        $bad['error'] = 'Не нашёл страницу-образец /' . GLOSSARY_DONOR . ' — из неё берутся шапка, подвал и шрифты.';
        return $bad;
    }
    $headEnd   = strpos($src, '</head>');
    $mainPos   = strpos($src, '<main');
    $mainOpen  = $mainPos !== false ? strpos($src, '>', $mainPos) : false;
    $mainClose = strpos($src, '</main>');
    if ($headEnd === false || $mainOpen === false || $mainClose === false || $mainClose < $mainOpen) {
        $bad['error'] = 'В странице-образце нет <head>, <main> или </main> — не могу собрать страницу.';
        return $bad;
    }
    $head  = substr($src, 0, $headEnd + 7);
    $open  = substr($src, $headEnd + 7, $mainOpen - $headEnd - 7 + 1);
    $close = substr($src, $mainClose);

    /* Подменяем только своё в мете: заголовок, описание, og и адрес канонической страницы. */
    $title = (string)($page['title'] ?? '');
    $desc  = (string)($page['description'] ?? '');
    $url   = (string)($page['url'] ?? '');
    $head  = (string)preg_replace('#<!--EDIT:title-->.*?<!--/EDIT:title-->#s',
        '<!--EDIT:title--><title>' . h($title) . '</title><!--/EDIT:title-->', $head, 1);
    $head  = (string)preg_replace('#<!--EDIT:description-->.*?<!--/EDIT:description-->#s',
        '<!--EDIT:description--><meta name="description" content="' . h($desc) . '" /><!--/EDIT:description-->', $head, 1);
    $head  = (string)preg_replace('#<!--EDIT:og-->.*?<!--/EDIT:og-->#s',
        "<!--EDIT:og-->\n  <meta property=\"og:title\" content=\"" . h($title) . "\" />\n"
        . "  <meta property=\"og:description\" content=\"" . h($desc) . "\" />\n<!--/EDIT:og-->", $head, 1);
    $head  = (string)preg_replace('#<link rel="canonical" href="[^"]*" />#',
        '<link rel="canonical" href="' . $url . '" />', $head, 1);
    $head  = (string)preg_replace('#<meta property="og:url" content="[^"]*" />#',
        '<meta property="og:url" content="' . $url . '" />', $head, 1);

    return array('ok' => true, 'error' => '', 'head' => $head, 'open' => $open, 'close' => $close);
}

/** Собрать страницу: каркас + содержимое <main> + разметка JSON-LD перед </body>. */
function glossary_page(array $page, string $body, string $jsonld = ''): array
{
    $shell = glossary_shell($page);
    if (!$shell['ok']) { return array('ok' => false, 'error' => $shell['error'], 'html' => ''); }
    $html = $shell['head'] . $shell['open'] . "\n" . $body . "\n" . $shell['close'];
    if ($jsonld !== '') {
        $html = (string)preg_replace('#</body>#', $jsonld . "\n</body>", $html, 1);
    }
    return array('ok' => true, 'error' => '', 'html' => $html);
}

