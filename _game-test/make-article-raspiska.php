/* ─────────────────── публикация ─────────────────── */

function say(string $line): void { echo $line . PHP_EOL; }

/** Видимый текст статьи одной строкой — для подсчёта знаков и слов (как в article_seo_warnings). */
function article_visible_text(array $f): string {
    $text = article_plain((string)($f['intro'] ?? ''));
    foreach ((array)($f['blocks'] ?? array()) as $b) {
        $text .= ' ' . article_plain((string)($b['text'] ?? ''));
        foreach ((array)($b['items'] ?? array()) as $it) { $text .= ' ' . article_plain((string)$it); }
        foreach (array('left', 'right') as $side) {
            foreach ((array)($b[$side]['items'] ?? array()) as $it) { $text .= ' ' . article_plain((string)$it); }
        }
        foreach ((array)($b['head'] ?? array()) as $th) { $text .= ' ' . article_plain((string)$th); }
        foreach ((array)($b['rows'] ?? array()) as $row) {
            foreach ((array)$row as $td) { $text .= ' ' . article_plain((string)$td); }
        }
    }
    foreach ((array)($f['faq'] ?? array()) as $item) { $text .= ' ' . article_plain((string)($item['a'] ?? '')); }
    return trim((string)preg_replace('/\s+/u', ' ', $text));
}

/** Есть ли у внутреннего адреса страница на сайте (проверка ссылок статьи). */
function link_exists(string $href): bool {
    if ($href === '' || $href[0] !== '/') { return true; }
    $p = SITE_ROOT . rtrim($href, '/');
    return is_file($p) || is_file($p . '/index.html') || is_dir($p);
}

