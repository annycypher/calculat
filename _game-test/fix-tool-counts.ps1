#
# Повод: на сайте остались устаревшие подписи. Фактически сейчас 29 калькуляторов
# (16 финансовых + 6 строительных + 4 авто + 3 инженерных), 7 генераторов документов
# и 6 конвертеров, а в текстах было «21 калькулятор», «15 калькуляторов» и «6 генераторов».
# Плюс в таблице на главной не было строк про авто и инженерные расчёты.
#
# Скрипт правит: шапку меню на всех страницах (цифра у «Финансы и налоги»), главную,
# «О проекте», хаб /calculators/ и хаб /calculators/finance/. Каждая замена проверяется:
# если строки нет или она не одна — скрипт останавливается, чтобы не испортить разметку.
param()
$ErrorActionPreference = 'Stop'
$enc = New-Object Text.UTF8Encoding($false)
$root = Split-Path -Parent $PSScriptRoot
$exclude = '\\(_backup|_archive|backups|_game-test|admin-panel)\\'

function Edit-Exact([string]$rel, [string]$old, [string]$new, [int]$expect = 1) {
  $path = Join-Path $root $rel
  $text = [IO.File]::ReadAllText($path)
  $count = ([regex]::Matches($text, [regex]::Escape($old))).Count
  if ($count -ne $expect) { throw "файл $rel : ожидалось $expect совпадений, найдено $count для «$old»" }
  [IO.File]::WriteAllText($path, $text.Replace($old, $new), $enc)
  Write-Output ("  " + $rel + " — заменено вхождений: " + $count)
}

# ── 1. Шапка меню: «Финансы и налоги» — 16 инструментов, а не 15 ──
$navOld = 'Финансы и налоги<b>15</b>'
$navNew = 'Финансы и налоги<b>16</b>'
$pages = Get-ChildItem -LiteralPath $root -Recurse -File -Filter *.html | Where-Object { $_.FullName -notmatch $exclude }
$touched = 0
foreach ($p in $pages) {
  $text = [IO.File]::ReadAllText($p.FullName)
  if (-not $text.Contains($navOld)) { continue }
  [IO.File]::WriteAllText($p.FullName, $text.Replace($navOld, $navNew), $enc)
  $touched++
}
Write-Output ("  шапка меню: обновлено страниц " + $touched)

