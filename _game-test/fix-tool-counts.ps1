$left = 0
foreach ($pat in '21 калькулятор', '21 инструмент', '15 калькулятор', '<b>15</b>', 'кредит и кредита') {
  $found = @($pages | Select-String -Pattern $pat -SimpleMatch)
  Write-Output ("  «" + $pat + "» -> " + $found.Count)
  $left += $found.Count
