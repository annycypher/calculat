<?php
/* len-check.php — служебная проверка на этапе описаний:
   1) длины присланных владельцем текстов;
   2) входят ли файлы из списка ссылок с главной в список описаний. */
declare(strict_types=1);
$root = dirname(__DIR__);
$given = [
    'главная'      => 'CalcDoc — бесплатные онлайн-калькуляторы, конвертеры величин и шаблоны документов. Расчёты и документы прямо в браузере, без регистрации.',
    'о проекте'    => 'О проекте CalcDoc: зачем созданы калькуляторы, конвертеры и конструктор документов, как работают разделы Calc и Doc.',
    'калькуляторы' => 'Бесплатные онлайн-калькуляторы: кредиты, проценты, даты, здоровье и другие расчёты. Точный результат в один клик, без регистрации.',
    'конвертеры'   => 'Онлайн-конвертеры величин и валют: длина, вес, объём, температура, валютные курсы. Быстрый и точный перевод единиц измерения.',
    'документы'    => 'Шаблоны и конструктор документов онлайн: договоры, заявления, доверенности. Заполните и скачайте бесплатно.',
];
foreach ($given as $k => $v) { echo str_pad($k, 14) . ' ' . mb_strlen($v) . " знаков\n"; }

$links = array_filter(array_map('trim', file((string)$root . '/shots/_upload-home-links.txt', FILE_IGNORE_NEW_LINES)));
$descs = array_filter(array_map('trim', file((string)$root . '/shots/_upload-descriptions.txt', FILE_IGNORE_NEW_LINES)));
$only = array_diff($links, $descs);
echo "\nфайлов в списке ссылок: " . count($links) . ", в списке описаний: " . count($descs) . "\n";
echo 'нет в списке описаний (нужно догрузить отдельно): ' . ($only ? implode(', ', $only) : 'нет — все входят') . "\n";
echo "объединённый список к выгрузке: " . count(array_unique(array_merge($links, $descs))) . " файлов\n";
